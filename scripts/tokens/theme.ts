import {
  lint,
  type DesignSystemState,
  type ResolvedColor,
  type ResolvedDimension,
  type ResolvedTypography,
  type ResolvedValue,
} from "@google/design.md/linter";

/**
 * theme.generated.css (contrib-engineering §4.2): the parts of the thin
 * mapping layer that come from DESIGN.md's front matter, read with the
 * package's own parser because `design.md export` drops them. Every value
 * is machine-copied; this file only decides how each value is written.
 */

/** DESIGN.md → Typography: one family, served by next/font as --font-archivo. */
const FONT_FAMILY_VARIABLES: Readonly<Partial<Record<string, string>>> = {
  Archivo: "var(--font-archivo)",
};

/** Colours that stay the same in both themes. None today: all have twins. */
export const THEME_INVARIANT_COLOURS: readonly string[] = [];

export const DARK_SUFFIX = "-dark";

/** OpenType numeric features → font-variant-numeric keywords. */
const NUMERIC_FEATURES: Readonly<Record<string, string>> = {
  tnum: "tabular-nums",
  pnum: "proportional-nums",
  lnum: "lining-nums",
  onum: "oldstyle-nums",
  zero: "slashed-zero",
};

const FOCUS_RING = "focus-ring";
const FOCUS_COLOUR = "focus";

const HEADER = [
  "/*",
  " * Generated by `pnpm tokens` (scripts/tokens/theme.ts) from the front matter",
  " * of DESIGN.md. Do not edit: change DESIGN.md, then run `pnpm tokens`.",
  " */",
].join("\n");

function formatNumber(value: number): string {
  return String(Number(value.toFixed(4)));
}

function formatDimension(value: ResolvedDimension): string {
  return `${formatNumber(value.value)}${value.unit}`;
}

function isColour(value: ResolvedValue | undefined): value is ResolvedColor {
  return typeof value === "object" && "type" in value && value.type === "color";
}

function isDimension(
  value: ResolvedValue | undefined,
): value is ResolvedDimension {
  return (
    typeof value === "object" && "type" in value && value.type === "dimension"
  );
}

/** `'wdth' 125` → `125%`. Width is the only axis set through tokens. */
export function fontStretch(name: string, token: ResolvedTypography): string {
  const variation = token.fontVariation;
  if (variation === undefined) {
    throw new Error(
      `typography.${name}: fontVariation (the wdth axis) is missing`,
    );
  }
  const match = /^\s*'wdth'\s+(\d+(?:\.\d+)?)\s*$/.exec(variation);
  if (!match?.[1]) {
    throw new Error(
      `typography.${name}: fontVariation must be exactly "'wdth' <number>", got "${variation}"`,
    );
  }
  return `${formatNumber(Number(match[1]))}%`;
}

/** `'tnum' 1, 'lnum' 1` → `tabular-nums lining-nums`; none → `normal`. */
export function fontVariantNumeric(
  name: string,
  token: ResolvedTypography,
): string {
  if (token.fontFeature === undefined) return "normal";
  const keywords = token.fontFeature.split(",").map((part) => {
    const match = /^\s*'([a-z0-9]{4})'\s+1\s*$/.exec(part);
    const keyword =
      match?.[1] === undefined ? undefined : NUMERIC_FEATURES[match[1]];
    if (keyword === undefined) {
      throw new Error(
        `typography.${name}: unsupported fontFeature "${part.trim()}" (supported: ${Object.keys(NUMERIC_FEATURES).join(", ")}, each set to 1)`,
      );
    }
    return keyword;
  });
  return keywords.join(" ");
}

/** Checks a role is complete and returns the CSS variable of its family. */
function familyVariable(name: string, token: ResolvedTypography): string {
  const { fontFamily, fontSize, fontWeight, lineHeight } = token;
  if (
    fontFamily === undefined ||
    fontSize === undefined ||
    fontWeight === undefined ||
    lineHeight === undefined
  ) {
    throw new Error(
      `typography.${name}: fontFamily, fontSize, fontWeight and lineHeight are all required`,
    );
  }
  const variable = FONT_FAMILY_VARIABLES[fontFamily];
  if (variable === undefined) {
    throw new Error(
      `typography.${name}: fontFamily "${fontFamily}" has no web font (known: ${Object.keys(FONT_FAMILY_VARIABLES).join(", ")})`,
    );
  }
  return variable;
}

function fontRepointing(designSystem: DesignSystemState): string {
  const lines = [...designSystem.typography].map(
    ([name, token]) => `  --font-${name}: ${familyVariable(name, token)};`,
  );
  return [
    '/* The exported family name "Archivo" resolves to next/font\'s face. */',
    "@theme inline {",
    ...lines,
    "}",
  ].join("\n");
}

function typeUtility(name: string, token: ResolvedTypography): string {
  const letterSpacing =
    token.letterSpacing === undefined ? "normal" : `var(--tracking-${name})`;
  return [
    `@utility type-${name} {`,
    `  font-family: ${familyVariable(name, token)};`,
    `  font-size: var(--text-${name});`,
    `  line-height: var(--leading-${name});`,
    `  letter-spacing: ${letterSpacing};`,
    `  font-weight: var(--font-weight-${name});`,
    `  font-stretch: ${fontStretch(name, token)};`,
    `  font-variant-numeric: ${fontVariantNumeric(name, token)};`,
    "}",
  ].join("\n");
}

function typeUtilities(designSystem: DesignSystemState): string {
  const comment = [
    "/* One utility per typography token. Width goes through font-stretch and",
    "   figures through font-variant-numeric, never font-variation-settings.",
    "   Roles without tracking or figures reset them, so nothing inherits. */",
  ].join("\n");
  return [
    comment,
    ...[...designSystem.typography].map(([name, token]) =>
      typeUtility(name, token),
    ),
  ].join("\n\n");
}

/** Each light colour and its dark value, in DESIGN.md order. */
export function darkSwaps(
  designSystem: DesignSystemState,
): readonly (readonly [string, string])[] {
  const swaps: (readonly [string, string])[] = [];
  for (const [name, colour] of designSystem.colors) {
    if (name.endsWith(DARK_SUFFIX)) {
      const base = name.slice(0, -DARK_SUFFIX.length);
      if (!designSystem.colors.has(base)) {
        throw new Error(`colors.${name} has no light colour "${base}"`);
      }
      continue;
    }
    const twin = designSystem.colors.get(`${name}${DARK_SUFFIX}`);
    if (twin === undefined) {
      if (THEME_INVARIANT_COLOURS.includes(name)) continue;
      throw new Error(
        `colors.${name} has no ${name}${DARK_SUFFIX} twin: add one to DESIGN.md, or list it in THEME_INVARIANT_COLOURS (colour ${colour.hex})`,
      );
    }
    swaps.push([name, twin.hex]);
  }
  return swaps;
}

function colourSchemes(designSystem: DesignSystemState): string {
  const declarations = darkSwaps(designSystem).map(
    ([name, hex]) => `--color-${name}: ${hex};`,
  );
  const block = (indent: string) => [
    `${indent}color-scheme: dark;`,
    ...declarations.map((declaration) => `${indent}${declaration}`),
  ];
  return [
    "/* Dark theme: every colour token takes its -dark value, in two places:",
    "   a stored choice (data-theme, Phase 4) and the system preference.",
    "   Literal values, because Tailwind emits only the theme variables it uses. */",
    "@layer base {",
    "  :root {",
    "    color-scheme: light;",
    "  }",
    "",
    '  :root[data-theme="dark"] {',
    ...block("    "),
    "  }",
    "",
    "  @media (prefers-color-scheme: dark) {",
    '    :root:not([data-theme="light"]) {',
    ...block("      "),
    "    }",
    "  }",
    "}",
  ].join("\n");
}

function focusRing(designSystem: DesignSystemState): string {
  const ring = designSystem.components.get(FOCUS_RING)?.properties;
  const colour = ring?.get("textColor");
  const width = ring?.get("size");
  const offset = ring?.get("padding");
  if (!isColour(colour) || !isDimension(width) || !isDimension(offset)) {
    throw new Error(
      `components.${FOCUS_RING} needs textColor, size (width) and padding (offset)`,
    );
  }
  // The resolved model keeps values, not references: check that the ring's
  // colour is the focus token, in both themes, before writing its variable.
  const focus = designSystem.colors.get(FOCUS_COLOUR);
  const focusDark = designSystem.colors.get(`${FOCUS_COLOUR}${DARK_SUFFIX}`);
  const ringDark = designSystem.components
    .get(`${FOCUS_RING}${DARK_SUFFIX}`)
    ?.properties.get("textColor");
  if (
    focus?.hex !== colour.hex ||
    !isColour(ringDark) ||
    focusDark?.hex !== ringDark.hex
  ) {
    throw new Error(
      `components.${FOCUS_RING} and ${FOCUS_RING}${DARK_SUFFIX} must use colors.${FOCUS_COLOUR} and colors.${FOCUS_COLOUR}${DARK_SUFFIX}`,
    );
  }
  return [
    "/* components.focus-ring: `size` is the width, `padding` the offset.",
    "   The dark ring comes from the colour swap above. */",
    "@layer base {",
    "  :focus-visible {",
    `    outline: ${formatDimension(width)} solid var(--color-${FOCUS_COLOUR});`,
    `    outline-offset: ${formatDimension(offset)};`,
    "  }",
    "}",
  ].join("\n");
}

/** The full theme.generated.css for a DESIGN.md source. */
export function buildTheme(designMd: string): string {
  const report = lint(designMd);
  if (report.summary.errors > 0) {
    throw new Error("DESIGN.md has lint errors: run `pnpm design:lint`");
  }
  const { designSystem } = report;
  return `${[
    HEADER,
    fontRepointing(designSystem),
    typeUtilities(designSystem),
    colourSchemes(designSystem),
    focusRing(designSystem),
  ].join("\n\n")}\n`;
}
